#include "task.h"
#include "oge_test.h"

int main(void)
{
    { const uint8_t d[] = {0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39}; CHECK_EQ_U(crc16_ccitt_false(d, 9), 0x29B1); }
    { const uint8_t d[] = {0}; CHECK_EQ_U(crc16_ccitt_false(d, 0), 0xFFFF); }
    { const uint8_t d[] = {0x00}; CHECK_EQ_U(crc16_ccitt_false(d, 1), 0xE1F0); }
    { const uint8_t d[] = {0xFF, 0xFF, 0xFF, 0xFF}; CHECK_EQ_U(crc16_ccitt_false(d, 4), 0x1D0F); }
    { const uint8_t d[] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F}; CHECK_EQ_U(crc16_ccitt_false(d, 32), 0x23B3); }
    { const uint8_t d[] = {0x46, 0x4C, 0x49, 0x47, 0x48, 0x54, 0x20, 0x53, 0x4F, 0x46, 0x54, 0x57, 0x41, 0x52, 0x45}; CHECK_EQ_U(crc16_ccitt_false(d, 15), 0x15CA); }
    CHECK_EQ_U(crc16_ccitt_false(NULL, 0), 0xFFFF);
    {
        const uint8_t d[] = "123456789";
        uint16_t c = crc16_ccitt_false(d, 4);
        c = crc16_ccitt_update(c, d + 4, 5);
        CHECK_EQ_U(c, 0x29B1);
        CHECK_EQ_U(crc16_ccitt_update(0xFFFF, d, 9), crc16_ccitt_false(d, 9));
        CHECK_EQ_U(crc16_ccitt_update(0x1234, NULL, 0), 0x1234);
    }
    return OGE_REPORT();
}
